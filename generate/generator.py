    f.write("import 'package:flutter_lucide/flutter_lucide.dart';\n\n")
    f.write("const Map<String, IconData> lucidData = {\n")

    for name in json_files:
        f.write(f'  "{name}": LucideIcons.{ALIASES.get(name, name)},\n')
    f.write("};")
